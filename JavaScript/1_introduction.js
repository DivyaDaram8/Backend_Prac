// This is the first JavaScript file.
// It demonstrates basic console output,
// variable usage, and simple operations.

// Printing a message to the console
console.log("Hello from first.js");

// Variable declaration
let fullName = "John Doe";
let age = 30;
let salary = 50000.50;
let isEmployed = true;
let x = null;
let y = undefined;

// Printing values
console.log("Full Name:", fullName);
console.log("Age:", age);
console.log("Salary:", salary);
console.log("Is Employed:", isEmployed);
console.log("X:", x); // null
console.log("Y:", y); // undefined

// Checking data types
console.log("Type of fullName:", typeof fullName);
console.log("Type of age:", typeof age);
console.log("Type of salary:", typeof salary);

// Performing simple operations
console.log("Salary after bonus:", salary + 1000);
console.log("Full Name with surname:", fullName + " Abraham");
